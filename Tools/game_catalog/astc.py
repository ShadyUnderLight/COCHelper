def decode_block(data: bytes, block_w: int, block_h: int) -> bytes:
    """解码单个 16 字节 ASTC 块 → RGBA8（block_w*block_h*4 字节，行优先）。

    块尺寸为参数（4x4 / 6x6 等）；支持 LDR 全端点、1-4 分区、dual-plane、
    const/void-extent。任何畸形/非法/未支持（HDR）输入抛 AstcError。
    """
    if len(data) < 16:
        raise AstcError(f"ASTC 块数据不足 16 字节: {len(data)}")
    buf = data[:16] + b"\x00\x00"  # 越界位读取 padding（ARM 读 2 字节）
    texel_count = block_w * block_h
    bm = _read_bits(buf, 11, 0)

    # --- const / void-extent 块（0xFC 家族）---
    if (bm & 0x1FF) == 0x1FC:
        if bm & 0x200:
            raise AstcError("F16 常量块未实现（HDR）")
        if _read_bits(buf, 2, 10) != 3:
            raise AstcError("void-extent 保留位不为 1")
        ext = [
            _read_bits(buf, 8, 12 + 13 * i) | (_read_bits(buf, 5, 20 + 13 * i) << 8)
            for i in range(2)
        ]
        ext += [
            _read_bits(buf, 8, 38 + 13 * (i - 2))
            | (_read_bits(buf, 5, 46 + 13 * (i - 2)) << 8)
            for i in range(2, 4)
        ]
        if any(ext[i] >= ext[i + 1] for i in (0, 2)) and not all(
            v == 0x1FFF for v in ext
        ):
            raise AstcError(f"void-extent 坐标非法: {ext}")
        color = tuple((data[8 + 2 * i] | (data[9 + 2 * i] << 8)) >> 8 for i in range(4))
        return bytes(color) * texel_count

    # --- 常规块 ---
    mode = _decode_block_mode(bm)
    if mode is None:
        raise AstcError(f"保留 block mode: 0x{bm:03x}")
    grid_w, grid_h, wquant, dual = mode
    if grid_w > block_w or grid_h > block_h:
        raise AstcError(
            f"权重网格 {grid_w}x{grid_h} 超过块尺寸 {block_w}x{block_h}（spec 非法块）"
        )
    wcount = grid_w * grid_h
    real_wcount = wcount * (2 if dual else 1)
    wbits = _ise_bits(real_wcount, wquant)
    if real_wcount > 64 or not (24 <= wbits <= 96):
        raise AstcError(
            f"权重配置非法: {wcount} 权重 {wbits} bits（spec 需 24..96 bits 且 ≤64 权重）"
        )

    partition_count = _read_bits(buf, 2, 11) + 1
    if dual and partition_count == 4:
        raise AstcError("dual-plane 与 4 分区同时出现（spec 非法组合）")

    # 权重（块尾部 LSB-first，字节位反转）
    bswapped = bytes(_BITREV8[buf[15 - i]] for i in range(16))
    raw_w = _decode_ise(wquant, real_wcount, bswapped, 0)
    unq = _WEIGHT_UNSCRAMBLE[wquant]
    if dual:
        # ARM：交错存储，weights[2i]=平面1[i]，weights[2i+1]=平面2[i]
        w1 = [unq[raw_w[2 * i]] for i in range(wcount)]
        w2 = [unq[raw_w[2 * i + 1]] for i in range(wcount)]
    else:
        w1 = [unq[v] for v in raw_w]
        w2 = None

    below_weights_pos = 128 - wbits

    # 颜色端点格式
    if partition_count == 1:
        cems = [_read_bits(buf, 4, 13)]
        partition_index = 0
        high_size = 0
    else:
        high_size = 3 * partition_count - 4
        below_weights_pos -= high_size  # INDIV 高位紧贴权重区下方（ARM）
        encoded = _read_bits(buf, 6, 23) | (
            _read_bits(buf, high_size, below_weights_pos) << 6
        )
        baseclass = encoded & 3
        if baseclass == 0:
            cems = [((encoded >> 2) & 0xF)] * partition_count
            below_weights_pos += high_size  # ALL 格式高位未用，恢复
            high_size = 0
        else:
            bitpos = 2
            baseclass -= 1
            cems = []
            for _ in range(partition_count):
                cems.append((((encoded >> bitpos) & 1) + baseclass) << 2)
                bitpos += 1
            for i in range(partition_count):
                cems[i] |= (encoded >> bitpos) & 3
                bitpos += 2
        partition_index = _read_bits(buf, 10, 13)

    # 颜色值数量
    color_integer_count = sum(2 * (cem >> 2) + 2 for cem in cems)
    if color_integer_count > 18:
        raise AstcError(f"颜色整数数 {color_integer_count} 超过 18（spec 非法）")

    color_bits = (111 if partition_count == 1 else 99) - wbits - high_size
    if dual:
        color_bits -= 2
    color_bits = max(0, color_bits)
    cquant = _QUANT_MODE_TABLE[color_integer_count >> 1][color_bits]
    if cquant < 4:  # QUANT_6 起（枚举值 4）；-1 或 <4 均为不可用
        raise AstcError(
            f"颜色可用位数不足（bits={color_bits} 值={color_integer_count}）"
        )

    color_off = 17 if partition_count == 1 else 29
    raw_c = _decode_ise(cquant, color_integer_count, buf, color_off)
    cu = _COLOR_UNSCRAMBLE[cquant - 4]
    color_values = [cu[v] for v in raw_c]

    # 端点
    endpoints = []
    pos = 0
    for cem in cems:
        n = 2 * (cem >> 2) + 2
        ep0, ep1, rgb_hdr, a_hdr = _unpack_endpoints(cem, color_values[pos : pos + n])
        if not rgb_hdr:
            ep0 = [c * 257 for c in ep0]
            ep1 = [c * 257 for c in ep1]
        endpoints.append((ep0, ep1, rgb_hdr, a_hdr))
        pos += n

    # plane2 分量（dual-plane）
    plane2_component = None
    if dual:
        plane2_component = _read_bits(buf, 2, below_weights_pos - 2)

    # 每 texel 权重插值 + 颜色 lerp
    contribs = _weight_contribs(block_w, block_h, grid_w, grid_h)
    parts = _partition_of_texel(partition_count, partition_index, block_w, block_h)
    out = bytearray(texel_count * 4)
    for t in range(texel_count):
        s = 0
        for q, w in contribs[t]:
            s += w1[q] * w
        tw = (s + 8) >> 4
        if dual:
            s2 = 0
            for q, w in contribs[t]:
                s2 += w2[q] * w
            tw2 = (s2 + 8) >> 4
        ep0, ep1, rgb_hdr, a_hdr = endpoints[parts[t]]
        px = bytearray(4)
        for c in range(4):
            w = tw2 if (dual and c == plane2_component) else tw
            v = (ep0[c] * (64 - w) + ep1[c] * w + 32) >> 6
            if (rgb_hdr and c < 3) or (a_hdr and c == 3):
                px[c] = _hdr16_to_u8(v)
            else:
                px[c] = v >> 8
        out[t * 4 : t * 4 + 4] = px
    return bytes(out)


def decode_region(
    data: bytes,
    width: int,
    height: int,
    block_w: int,
    block_h: int,
    x0: int,
    y0: int,
    x1: int,
    y1: int,
) -> bytes:
    """解码图像 (x0,y0)-(x1,y1) 区域 → 区域 RGBA8（(x1-x0)*(y1-y0)*4 字节）。

    只解码覆盖区域的块（行块/列块裁剪），供渲染管线局部刷新；区域越界由
    调用方保证（或按行块取整）。块数据必须完整（含边界块）。
    """
    if not (0 <= x0 < x1 <= width and 0 <= y0 < y1 <= height):
        raise AstcError(f"区域越界: ({x0},{y0})-({x1},{y1}) 图像 {width}x{height}")
    bw = (width + block_w - 1) // block_w
    out = bytearray((x1 - x0) * (y1 - y0) * 4)
    for by in range(y0 // block_h, (y1 - 1) // block_h + 1):
        for bx in range(x0 // block_w, (x1 - 1) // block_w + 1):
            blk = data[(by * bw + bx) * 16 : (by * bw + bx + 1) * 16]
            px = decode_block(blk, block_w, block_h)
            src_x = max(x0, bx * block_w)
            src_y = max(y0, by * block_h)
            end_x = min(x1, (bx + 1) * block_w)
            end_y = min(y1, (by + 1) * block_h)
            for yy in range(src_y, end_y):
                src_off = ((yy - by * block_h) * block_w + (src_x - bx * block_w)) * 4
                dst_off = ((yy - y0) * (x1 - x0) + (src_x - x0)) * 4
                n = (end_x - src_x) * 4
                out[dst_off : dst_off + n] = px[src_off : src_off + n]
    return bytes(out)
