# ---------------------------------------------------------------------------
# 位读取
# ---------------------------------------------------------------------------


def _read_bits(data: bytes, bitcount: int, bitoffset: int) -> int:
    """读 data 的 bitoffset 起 bitcount 位（跨字节；data 需含越界 padding）。"""
    b = bitoffset >> 3
    off = bitoffset & 7
    return ((data[b] | (data[b + 1] << 8)) >> off) & ((1 << bitcount) - 1)


def _ise_bits(count: int, quant: int) -> int:
    scale, divisor = _ISE_SIZES[quant]
    return (scale * count + divisor - 1) // divisor


def _decode_ise(quant: int, count: int, data: bytes, bitoffset: int) -> list[int]:
    """BISE 解码（ARM decode_ise 逐字移植）。返回 count 个 raw 值。

    值流：每个值先读 `bits` 位 LSB，再按块位置读 trit/quint 位（trit 块 5
    值 8 位、quint 块 3 值 7 位），最后用 _TRITS/_QUINTS_OF_INTEGER 表还原。
    """
    bits, trits, quints = _BTQ[quant]
    results = [0] * (count + 4)
    tq_blocks = [0] * 22
    lcounter = 0
    hcounter = 0
    pos = bitoffset
    for i in range(count):
        results[i] = _read_bits(data, bits, pos)
        pos += bits
        if trits:
            bits_to_read = (2, 2, 1, 2, 1)
            block_shift = (0, 2, 4, 5, 7)
            next_lc = (1, 2, 3, 4, 0)
            hinc = (0, 0, 0, 0, 1)
            tdata = _read_bits(data, bits_to_read[lcounter], pos)
            pos += bits_to_read[lcounter]
            tq_blocks[hcounter] |= tdata << block_shift[lcounter]
            hcounter += hinc[lcounter]
            lcounter = next_lc[lcounter]
        if quints:
            bits_to_read = (3, 2, 2)
            block_shift = (0, 3, 5)
            next_lc = (1, 2, 0)
            hinc = (0, 0, 1)
            qdata = _read_bits(data, bits_to_read[lcounter], pos)
            pos += bits_to_read[lcounter]
            tq_blocks[hcounter] |= qdata << block_shift[lcounter]
            hcounter += hinc[lcounter]
            lcounter = next_lc[lcounter]
    if trits:
        for i in range((count + 4) // 5):
            row = _TRITS_OF_INTEGER[tq_blocks[i]]
            for j in range(5):
                results[5 * i + j] |= row[j] << bits
    if quints:
        for i in range((count + 2) // 3):
            row = _QUINTS_OF_INTEGER[tq_blocks[i]]
            for j in range(3):
                results[3 * i + j] |= row[j] << bits
    return results[:count]


# ---------------------------------------------------------------------------
# block mode 解析（ARM decode_block_mode_2d；与 KDF spec Table 23.9 一致）
# ---------------------------------------------------------------------------


def _decode_block_mode(bm: int) -> tuple[int, int, int, bool] | None:
    """(权重网格宽, 高, 权重 quant 0..11, dual_plane)；保留模式 → None。"""
    base_quant = (bm >> 4) & 1
    h_bit = (bm >> 9) & 1
    dual = bool((bm >> 10) & 1)
    a = (bm >> 5) & 3
    if bm & 3:
        base_quant |= (bm & 3) << 1
        b = (bm >> 7) & 3
        sw = (bm >> 2) & 3
        if sw == 0:
            wx, wy = b + 4, a + 2
        elif sw == 1:
            wx, wy = b + 8, a + 2
        elif sw == 2:
            wx, wy = a + 2, b + 8
        else:
            b &= 1
            if bm & 0x100:
                wx, wy = b + 2, a + 2
            else:
                wx, wy = a + 2, b + 6
    else:
        base_quant |= ((bm >> 2) & 3) << 1
        if ((bm >> 2) & 3) == 0:
            return None
        b = (bm >> 9) & 3
        sw = (bm >> 7) & 3
        if sw == 0:
            wx, wy = 12, a + 2
        elif sw == 1:
            wx, wy = a + 2, 12
        elif sw == 2:
            wx, wy = a + 6, b + 6
            dual = False
            h_bit = 0
        else:
            sw2 = (bm >> 5) & 3
            if sw2 == 0:
                wx, wy = 6, 10
            elif sw2 == 1:
                wx, wy = 10, 6
            else:
                return None
    return wx, wy, (base_quant - 2) + 6 * h_bit, dual


# ---------------------------------------------------------------------------
# partition 过程式生成（KDF spec §23.10 / ARM astcenc_partition_tables.cpp）
# ---------------------------------------------------------------------------


def _hash52(inp: int) -> int:
    inp ^= inp >> 15
    inp = (inp * 0xEEDE0891) & 0xFFFFFFFF
    inp ^= inp >> 5
    inp = (inp + (inp << 16)) & 0xFFFFFFFF
    inp ^= inp >> 7
    inp ^= inp >> 3
    inp ^= (inp << 6) & 0xFFFFFFFF
    inp ^= inp >> 17
    return inp & 0xFFFFFFFF


def _select_partition(
    seed: int, x: int, y: int, partition_count: int, small_block: bool
) -> int:
    if small_block:
        x <<= 1
        y <<= 1
    seed += (partition_count - 1) * 1024
    rnum = _hash52(seed)
    seeds = [(rnum >> (4 * i)) & 0xF for i in range(8)]
    seeds += [
        (rnum >> 18) & 0xF,
        (rnum >> 22) & 0xF,
        (rnum >> 26) & 0xF,
        ((rnum >> 30) | (rnum << 2)) & 0xF,
    ]
    seeds = [s * s for s in seeds]
    if seed & 1:
        sh1 = 4 if seed & 2 else 5
        sh2 = 6 if partition_count == 3 else 5
    else:
        sh1 = 6 if partition_count == 3 else 5
        sh2 = 4 if seed & 2 else 5
    # sh3 仅用于 seed9..12（z 项），2D 块 z=0 不使用
    s1, s2, s3, s4 = seeds[0] >> sh1, seeds[1] >> sh2, seeds[2] >> sh1, seeds[3] >> sh2
    s5, s6, s7, s8 = seeds[4] >> sh1, seeds[5] >> sh2, seeds[6] >> sh1, seeds[7] >> sh2
    # 2D 块 z=0：seed9..12 只参与 seedN*z 项，为 0（ARM: seedN * z）
    a = s1 * x + s2 * y + (rnum >> 14)
    b = s3 * x + s4 * y + (rnum >> 10)
    c = s5 * x + s6 * y + (rnum >> 6)
    d = s7 * x + s8 * y + (rnum >> 2)
    a &= 0x3F
    b &= 0x3F
    c &= 0x3F
    d &= 0x3F
    if partition_count <= 3:
        d = 0
    if partition_count <= 2:
        c = 0
    if a >= b and a >= c and a >= d:
        return 0
    if b >= c and b >= d:
        return 1
    if c >= d:
        return 2
    return 3


def _partition_of_texel(
    partition_count: int, seed: int, block_w: int, block_h: int
) -> list[int]:
    """返回每个 texel（行优先）的 partition 编号。"""
    small = block_w * block_h < 32
    out = [0] * (block_w * block_h)
    for y in range(block_h):
        for x in range(block_w):
            out[y * block_w + x] = _select_partition(seed, x, y, partition_count, small)
    return out


# ---------------------------------------------------------------------------
# 权重双线性插值（ARM init_decimation_info_2d）
# ---------------------------------------------------------------------------


def _weight_contribs(
    block_w: int, block_h: int, grid_w: int, grid_h: int
) -> list[list[tuple[int, int, int]]]:
    """每个 texel 的 (网格索引, 权重系数, 数量) 列表；权重和为 16。"""
    scale_x = (1024 + block_w // 2) // (block_w - 1) if block_w > 1 else 1024
    scale_y = (1024 + block_h // 2) // (block_h - 1) if block_h > 1 else 1024
    out = []
    for y in range(block_h):
        for x in range(block_w):
            xw = (scale_x * x * (grid_w - 1) + 32) >> 6
            yw = (scale_y * y * (grid_h - 1) + 32) >> 6
            xf, yf = xw & 0xF, yw & 0xF
            xi, yi = xw >> 4, yw >> 4
            q0 = xi + yi * grid_w
            prod = xf * yf
            w3 = (prod + 8) >> 4
            w1 = xf - w3
            w2 = yf - w3
            w0 = 16 - xf - yf + w3
            contribs = []
            for q, w in (
                (q0, w0),
                (q0 + 1, w1),
                (q0 + grid_w, w2),
                (q0 + grid_w + 1, w3),
            ):
                if w:
                    contribs.append((q, w))
            out.append(contribs)
    return out


# ---------------------------------------------------------------------------
# LDR 端点解码（ARM astcenc_color_unquantize.cpp 的 LDR 部分）
# ---------------------------------------------------------------------------


def _uncontract(color: list[int]) -> list[int]:
    r, g, b, a = color
    return [((r + b) >> 1), ((g + b) >> 1), b, a]


def _bit_transfer_signed(base: int, delta: int) -> tuple[int, int]:
    """位转移（ARM bit_transfer_signed；base 拿 delta 高 1 位，delta 符号扩展）。"""
    base = (base >> 1) | (delta & 0x80)
    delta = (delta >> 1) & 0x3F
    if delta & 0x20:
        delta -= 0x40
    return base, delta


def _unpack_endpoints(
    fmt: int, values: list[int]
) -> tuple[list[int], list[int], bool, bool]:
    """CEM 端点格式 → (端点0, 端点1, rgb_hdr, alpha_hdr)。

    返回 16-bit 端点：LDR = 8-bit 值（调用方 ×257 展开），HDR = 12-bit LNS << 4。
    HDR 端点按 spec §23 的 HDR endpoint modes 解码（ARM 逐字移植）。
    """
    if fmt == 0:  # LUMINANCE direct
        return ([values[0]] * 3 + [255], [values[1]] * 3 + [255], False, False)
    if fmt == 1:  # LUMINANCE delta
        v0, v1 = values
        l0 = (v0 >> 2) | (v1 & 0xC0)
        l1 = min(l0 + (v1 & 0x3F), 255)
        return ([l0] * 3 + [255], [l1] * 3 + [255], False, False)
    if fmt == 2:  # HDR LUMINANCE large range
        v0, v1 = values
        if v1 >= v0:
            y0, y1 = v0 << 4, v1 << 4
        else:
            y0, y1 = (v1 << 4) + 8, (v0 << 4) - 8
        y0, y1 = max(y0, 0), max(y1, 0)
        return ([y0 << 4] * 3 + [0x7800], [y1 << 4] * 3 + [0x7800], True, True)
    if fmt == 3:  # HDR LUMINANCE small range
        v0, v1 = values
        if v0 & 0x80:
            y0 = ((v1 & 0xE0) << 4) | ((v0 & 0x7F) << 2)
            y1 = (v1 & 0x1F) << 2
        else:
            y0 = ((v1 & 0xF0) << 4) | ((v0 & 0x7F) << 1)
            y1 = (v1 & 0xF) << 1
        y1 = min(y1 + y0, 0xFFF)
        return ([y0 << 4] * 3 + [0x7800], [y1 << 4] * 3 + [0x7800], True, True)
    if fmt == 4:  # LUMINANCE_ALPHA direct
        l0, l1, a0, a1 = values
        return ([l0] * 3 + [a0], [l1] * 3 + [a1], False, False)
    if fmt == 5:  # LUMINANCE_ALPHA delta
        lum0, lum1, alpha0, alpha1 = values
        lum0 |= (lum1 & 0x80) << 1
        alpha0 |= (alpha1 & 0x80) << 1
        lum1 &= 0x7F
        alpha1 &= 0x7F
        lum1 -= 0x80 if lum1 & 0x40 else 0
        alpha1 -= 0x80 if alpha1 & 0x40 else 0
        lum0 >>= 1
        lum1 >>= 1
        alpha0 >>= 1
        alpha1 >>= 1
        lum1 += lum0
        alpha1 += alpha0
        lum1 = max(0, min(255, lum1))
        alpha1 = max(0, min(255, alpha1))
        return ([lum0] * 3 + [alpha0], [lum1] * 3 + [alpha1], False, False)
    if fmt == 6:  # RGB base+scale
        r0, g0, b0, scale = values
        ep1 = [r0, g0, b0, 255]
        ep0 = [(r0 * scale) >> 8, (g0 * scale) >> 8, (b0 * scale) >> 8, 255]
        return (ep0, ep1, False, False)
    if fmt == 7:  # HDR RGB base+scale
        return _hdr_rgbo(values)
    if fmt == 8:  # RGB direct（值交错：R0,R1,G0,G1,B0,B1）
        ep0 = [values[0], values[2], values[4], 255]
        ep1 = [values[1], values[3], values[5], 255]
        ep0, ep1 = _maybe_uncontract(ep0, ep1)
        return (ep0, ep1, False, False)
    if fmt == 9:  # RGB delta
        v0, v1 = _bit_transfer_signed(values[0], values[1])
        v2, v3 = _bit_transfer_signed(values[2], values[3])
        v4, v5 = _bit_transfer_signed(values[4], values[5])
        ep0 = [v0, v2, v4, 255]
        ep1 = [v0 + v1, v2 + v3, v4 + v5, 255]
        if v1 + v3 + v5 < 0:  # ARM：bit_transfer 后 delta 之和 < 0
            ep0 = _uncontract(ep0)
            ep1 = _uncontract(ep1)
            ep0, ep1 = ep1, ep0
        ep0 = [max(0, min(255, c)) for c in ep0]
        ep1 = [max(0, min(255, c)) for c in ep1]
        return (ep0, ep1, False, False)
    if fmt == 10:  # RGB base+scale + alpha
        r0, g0, b0, scale, a0, a1 = values
        ep1 = [r0, g0, b0, a1]
        ep0 = [(r0 * scale) >> 8, (g0 * scale) >> 8, (b0 * scale) >> 8, a0]
        return (ep0, ep1, False, False)
    if fmt == 11:  # HDR RGB direct
        return _hdr_rgb(values)
    if fmt == 12:  # RGBA direct（值交错：R0,R1,G0,G1,B0,B1,A0,A1）
        ep0 = [values[0], values[2], values[4], values[6]]
        ep1 = [values[1], values[3], values[5], values[7]]
        ep0, ep1 = _maybe_uncontract(ep0, ep1)
        return (ep0, ep1, False, False)
    if fmt == 13:  # RGBA delta
        vals = values
        outs = [_bit_transfer_signed(vals[i], vals[i + 1]) for i in (0, 2, 4, 6)]
        ep0 = [o[0] for o in outs]
        ep1 = [o[0] + o[1] for o in outs]
        if outs[0][1] + outs[1][1] + outs[2][1] < 0:  # ARM：RGB delta 之和 < 0
            ep0 = _uncontract(ep0)
            ep1 = _uncontract(ep1)
            ep0, ep1 = ep1, ep0
        ep0 = [max(0, min(255, c)) for c in ep0]
        ep1 = [max(0, min(255, c)) for c in ep1]
        return (ep0, ep1, False, False)
    if fmt == 14:  # HDR RGB + LDR alpha
        ep0, ep1, _, _ = _hdr_rgb(values[:6])
        ep0[3] = values[6]
        ep1[3] = values[7]
        return (ep0, ep1, True, False)
    if fmt == 15:  # HDR RGB + HDR alpha
        ep0, ep1, _, _ = _hdr_rgb(values[:6])
        a0, a1 = _hdr_alpha(values[6:8])
        ep0[3], ep1[3] = a0, a1
        return (ep0, ep1, True, True)
    raise AstcError(f"未知端点格式 CEM {fmt}")


def _hdr_rgbo(values: list[int]) -> tuple[list[int], list[int], bool, bool]:
    """HDR RGB base+scale（CEM 7；ARM hdr_rgbo_unpack）。"""
    v0, v1, v2, v3 = values
    modeval = ((v0 & 0xC0) >> 6) | (((v1 & 0x80) >> 7) << 2) | (((v2 & 0x80) >> 7) << 3)
    if (modeval & 0xC) != 0xC:
        majcomp = modeval >> 2
        mode = modeval & 3
    elif modeval != 0xF:
        majcomp = modeval & 3
        mode = 4
    else:
        majcomp = 0
        mode = 5
    red = v0 & 0x3F
    green = v1 & 0x1F
    blue = v2 & 0x1F
    scale = v3 & 0x1F
    bit0 = (v1 >> 6) & 1
    bit1 = (v1 >> 5) & 1
    bit2 = (v2 >> 6) & 1
    bit3 = (v2 >> 5) & 1
    bit4 = (v3 >> 7) & 1
    bit5 = (v3 >> 6) & 1
    bit6 = (v3 >> 5) & 1
    ohcomp = 1 << mode
    if ohcomp & 0x30:
        green |= bit0 << 6
    if ohcomp & 0x3A:
        green |= bit1 << 5
    if ohcomp & 0x30:
        blue |= bit2 << 6
    if ohcomp & 0x3A:
        blue |= bit3 << 5
    if ohcomp & 0x3D:
        scale |= bit6 << 5
    if ohcomp & 0x2D:
        scale |= bit5 << 6
    if ohcomp & 0x04:
        scale |= bit4 << 7
    if ohcomp & 0x3B:
        red |= bit4 << 6
    if ohcomp & 0x04:
        red |= bit3 << 6
    if ohcomp & 0x10:
        red |= bit5 << 7
    if ohcomp & 0x0F:
        red |= bit2 << 7
    if ohcomp & 0x05:
        red |= bit1 << 8
    if ohcomp & 0x0A:
        red |= bit0 << 8
    if ohcomp & 0x05:
        red |= bit0 << 9
    if ohcomp & 0x02:
        red |= bit6 << 9
    if ohcomp & 0x01:
        red |= bit3 << 10
    if ohcomp & 0x02:
        red |= bit5 << 10
    shamt = (1, 1, 2, 3, 4, 5)[mode]
    red <<= shamt
    green <<= shamt
    blue <<= shamt
    scale <<= shamt
    if mode != 5:
        green = red - green
        blue = red - blue
    if majcomp == 1:
        red, green = green, red
    elif majcomp == 2:
        red, blue = blue, red
    red0 = max(red - scale, 0)
    green0 = max(green - scale, 0)
    blue0 = max(blue - scale, 0)
    red = max(red, 0)
    green = max(green, 0)
    blue = max(blue, 0)
    return (
        [red0 << 4, green0 << 4, blue0 << 4, 0x7800],
        [red << 4, green << 4, blue << 4, 0x7800],
        True,
        True,
    )


def _hdr_rgb(values: list[int]) -> tuple[list[int], list[int], bool, bool]:
    """HDR RGB direct（CEM 11；ARM hdr_rgb_unpack）。"""
    v0, v1, v2, v3, v4, v5 = values
    modeval = ((v1 & 0x80) >> 7) | (((v2 & 0x80) >> 7) << 1) | (((v3 & 0x80) >> 7) << 2)
    majcomp = ((v4 & 0x80) >> 7) | (((v5 & 0x80) >> 7) << 1)
    if majcomp == 3:
        return (
            [v0 << 8, v2 << 8, (v4 & 0x7F) << 9, 0x7800],
            [v1 << 8, v3 << 8, (v5 & 0x7F) << 9, 0x7800],
            True,
            True,
        )
    a = v0 | ((v1 & 0x40) << 2)
    b0 = v2 & 0x3F
    b1 = v3 & 0x3F
    c = v1 & 0x3F
    d0 = v4 & 0x7F
    d1 = v5 & 0x7F
    dbits = (7, 6, 7, 6, 5, 6, 5, 6)[modeval]
    bit0 = (v2 >> 6) & 1
    bit1 = (v3 >> 6) & 1
    bit2 = (v4 >> 6) & 1
    bit3 = (v5 >> 6) & 1
    bit4 = (v4 >> 5) & 1
    bit5 = (v5 >> 5) & 1
    ohmod = 1 << modeval
    if ohmod & 0xA4:
        a |= bit0 << 9
    if ohmod & 0x8:
        a |= bit2 << 9
    if ohmod & 0x50:
        a |= bit4 << 9
    if ohmod & 0x50:
        a |= bit5 << 10
    if ohmod & 0xA0:
        a |= bit1 << 10
    if ohmod & 0xC0:
        a |= bit2 << 11
    if ohmod & 0x4:
        c |= bit1 << 6
    if ohmod & 0xE8:
        c |= bit3 << 6
    if ohmod & 0x20:
        c |= bit2 << 7
    if ohmod & 0x5B:
        b0 |= bit0 << 6
        b1 |= bit1 << 6
    if ohmod & 0x12:
        b0 |= bit2 << 7
        b1 |= bit3 << 7
    if ohmod & 0xAF:
        d0 |= bit4 << 5
        d1 |= bit5 << 5
    if ohmod & 0x5:
        d0 |= bit2 << 6
        d1 |= bit3 << 6
    # d0/d1 符号扩展（dbits 位有符号）
    for vv in (d0, d1):
        if vv & (1 << (dbits - 1)):
            vv -= 1 << dbits
    val_shamt = (modeval >> 1) ^ 3
    a <<= val_shamt
    b0 <<= val_shamt
    b1 <<= val_shamt
    c <<= val_shamt
    d0 <<= val_shamt
    d1 <<= val_shamt
    red1 = a
    green1 = a - b0
    blue1 = a - b1
    red0 = a - c
    green0 = a - b0 - c - d0
    blue0 = a - b1 - c - d1
    red0 = max(0, min(4095, red0))
    green0 = max(0, min(4095, green0))
    blue0 = max(0, min(4095, blue0))
    red1 = max(0, min(4095, red1))
    green1 = max(0, min(4095, green1))
    blue1 = max(0, min(4095, blue1))
    if majcomp == 1:
        red0, green0 = green0, red0
        red1, green1 = green1, red1
    elif majcomp == 2:
        red0, blue0 = blue0, red0
        red1, blue1 = blue1, red1
    return (
        [red0 << 4, green0 << 4, blue0 << 4, 0x7800],
        [red1 << 4, green1 << 4, blue1 << 4, 0x7800],
        True,
        True,
    )


def _hdr_alpha(values: list[int]) -> tuple[int, int]:
    """HDR alpha（CEM 15；ARM hdr_alpha_unpack）。返回 16-bit（12-bit << 4）。"""
    v6, v7 = values
    modeval = ((v6 >> 7) & 1) | ((v7 >> 6) & 2)
    v6 &= 0x7F
    v7 &= 0x7F
    if modeval == 3:
        a0, a1 = v6 << 5, v7 << 5
    else:
        v6 |= (v7 << (modeval + 1)) & 0x780
        v7 &= 0x3F >> modeval
        v7 ^= 32 >> modeval
        v7 -= 32 >> modeval
        v6 <<= 4 - modeval
        v7 <<= 4 - modeval
        a0, a1 = v6, max(0, min(0xFFF, v6 + v7))
    return a0 << 4, a1 << 4


def _hdr16_to_u8(c16: int) -> int:
    """HDR 插值结果（16-bit）→ RGBA8：spec piecewise-log 修正 + fp16 → clamp u8。"""
    e = (c16 & 0xF800) >> 11
    m = c16 & 0x7FF
    if m < 512:
        mt = 3 * m
    elif m >= 1536:
        mt = 5 * m - 2048
    else:
        mt = 4 * m - 512
    cf = (e << 10) + (mt >> 3)  # fp16 位模式（无符号半精度）
    e2 = (cf >> 10) & 0x1F
    m2 = cf & 0x3FF
    if e2 == 0:
        f = m2 / 2**24
    else:
        f = (1 + m2 / 1024) * (2.0 ** (e2 - 15))
    v = int(f * 255 + 0.5)
    return max(0, min(255, v))


def _maybe_uncontract(ep0: list[int], ep1: list[int]) -> tuple[list[int], list[int]]:
    """RGB/RGBA direct：蓝收缩反向（sum0 > sum1 时）。"""
    if sum(ep0[:3]) > sum(ep1[:3]):
        ep0 = _uncontract(ep0)
        ep1 = _uncontract(ep1)
        return (ep1, ep0)
    return (ep0, ep1)


